const BRAILLE_MAP = {
  a: '⠁', b: '⠃', c: '⠉', d: '⠙', e: '⠑', f: '⠋', g: '⠛', h: '⠓',
  i: '⠊', j: '⠚', k: '⠅', l: '⠇', m: '⠍', n: '⠝', o: '⠕', p: '⠏',
  q: '⠟', r: '⠗', s: '⠎', t: '⠞', u: '⠥', v: '⠧', w: '⠺', x: '⠭',
  y: '⠽', z: '⠵',
  '1': '⠁', '2': '⠃', '3': '⠉', '4': '⠙', '5': '⠑',
  '6': '⠋', '7': '⠛', '8': '⠓', '9': '⠊', '0': '⠚',
  '.': '⠲', ',': '⠂', ';': '⠆', ':': '⠒', '?': '⠦', '!': '⠖',
  '-': '⠤', '(': '⠷', ')': '⠾', '/': '⠌', ' ': ' ',
  '\n': '\n',
};

export function textToBraille(text) {
  return text
    .toLowerCase()
    .split('')
    .map((char) => BRAILLE_MAP[char] || `⠿`)
    .join('');
}

export function generateBRFContent(text, title = 'Document') {
  const header = `# ${title}\n# Generated by AccessLearner\n# Grade 1 Braille (UEB)\n#\n`;
  const brailleText = textToBraille(text);
  const lines = brailleText.split('\n');
  const wrapped = lines.map((line) => {
    if (line.length <= 40) return line;
    const chunks = [];
    for (let i = 0; i < line.length; i += 40) {
      chunks.push(line.slice(i, i + 40));
    }
    return chunks.join('\n');
  });
  return header + wrapped.join('\n') + '\n';
}

export function downloadBRF(text, filename = 'document.brf') {
  const content = generateBRFContent(text, filename.replace('.brf', ''));
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
